extern u32 JW_GetResSizeFileNo(int res_no) {
    u32 res_size = 0;

    if (res_no >= RESOURCE_FGDATA && res_no < RESOURCE_FGNPCDATA) {
        CSDIFileEntry* entry = JC__JKRGetResourceEntry_byName((u32)'DATA', aram_resName[res_no], forest_arc_aram_p);

        if (entry != nullptr) {
            res_size = entry->mSize;
        }
    } else if (res_no < RESOURCE_MESSAGE) {
        CSDIFileEntry* entry = JC__JKRGetResourceEntry_byName((u32)'DATA', aram_resName[res_no], forest_arc_aram2_p);

        if (entry != nullptr) {
            res_size = entry->mSize;
        }
    } else if (res_no < RESOURCE_MAIL) {
        CSDIFileEntry* entry =
            JC__JKRGetResourceEntry_byName((u32)'DATA', aram_resName[res_no], forest_arc_aram_msg_p);

        if (entry != nullptr) {
            res_size = entry->mSize;
        }
    } else if (res_no < RESOURCE_NUM) {
        CSDIFileEntry* entry =
            JC__JKRGetResourceEntry_byName((u32)'DATA', aram_resName[res_no], forest_arc_aram_script_p);

        if (entry != nullptr) {
            res_size = entry->mSize;
        }
    }

    return res_size;
}

#define FIX_ARENA_LO 0x8029C000
#define FIX_ARENA_HI 0x817FFBC0

u32 JW_soundAramSize = 0x820000;

extern void JW_Init() {
    void* arenaLo = OSGetArenaLo();
    void* arenaHi = OSGetArenaHi();

    if ((u32)arenaLo <= FIX_ARENA_LO) {
        OSSetArenaLo((void*)FIX_ARENA_LO);
    } else {
        OSReport("\x1b[43;30mWARNING: ArenaLo(%x) > %x\x1b[m\n", arenaLo, FIX_ARENA_LO);
    }

    if ((u32)arenaHi != FIX_ARENA_HI && (u32)arenaHi < 0x81800000) {
        OSReport("\x1b[43;30mWARNING: ArenaHi(%x) != %x\x1b[m\n", arenaHi, OSGetArenaHi);
    }

    SystemHeapSize = (u32)OSGetArenaHi() - (u32)OSGetArenaLo() - 0xD0;
    JC_JFWSystem_setMaxStdHeap(1);
    JC_JFWSystem_setSysHeapSize(SystemHeapSize);
    JC_JFWSystem_setFifoBufSize(0x10001);

    u32 soundAramSize = JW_soundAramSize;
    u32 graphAramSize = 0x709960;
    OSReport("soundAramSize=%08x graphAramSize=%08x totalAramSize=%08x\n", soundAramSize, graphAramSize,
             soundAramSize + graphAramSize);
    JC_JFWSystem_setAramAudioBufSize(soundAramSize);
    JC_JFWSystem_setAramGraphBufSize(graphAramSize);
    JFWSystem::setRenderMode(&customized_GXNtsc480IntDf);
    JC_JFWSystem_init();
    JKRSetAramTransferBuffer((u8*)JKRAllocFromSysHeap(0x1000, 0), 0x1000, nullptr);
    JC_JKRExpHeap_changeGroupID(JC_JFWSystem_getSystemHeap(), 1);
    jc_sysConsole = JC_JFWSystem_getSystemConsole();
    JC_JUTConsole_setOutput(jc_sysConsole, 3);
    JC_JUTConsole_setPosition(jc_sysConsole, 32, 42);
    JC_JUTConsole_print(jc_sysConsole, "JC_JUTConsole START\n");
    JC_JUTConsole_print_f(jc_sysConsole, "Initial Arena = %x-%x\n", arenaLo, arenaHi);
    JC_JUTConsole_print_f(jc_sysConsole, "    Fix Arena = %x-%x\n", FIX_ARENA_LO, FIX_ARENA_HI);
    JC_JUTConsole_print_f(jc_sysConsole,
                          "FontEnc %x Lang %x SoundMode %x\nProgMode %x ConsType %x\nSimMem %x PhyMem %x ResetCode %x\n",
                          OSGetFontEncode(), OSGetLanguage(), OSGetSoundMode(), OSGetProgressiveMode(),
                          OSGetConsoleType(), OSGetConsoleSimulatedMemSize(), OSGetPhysicalMemSize(),
                          OSGetResetCode());
    JC_JUTConsole_print_f(jc_sysConsole, "DTVStatus %x ProgressiveMode %x EuRGB60Mode %x\n", VIGetDTVStatus(),
                          OSGetProgressiveMode(), OSGetEuRgb60Mode());

    OSTime time = OSGetTime() - __OSStartTime;
    OSCalendarTime cal;
    OSTicksToCalendarTime(time, &cal);
    JC_JUTConsole_print_f(jc_sysConsole, "%04d-%02d-%02d %02d:%02d:%02d'%03d''%03d(%016llx)\n", cal.year, cal.mon,
                          cal.mday, cal.hour, cal.min, cal.sec, cal.msec, cal.usec, time);

    void* display_manager = JC_JFWDisplay_createManager_0(JC_JFWSystem_getSystemHeap(), 2, 1);
    JC_JUTProcBar_setVisible(JC_JUTProcBar_getManager(), FALSE);
    JC_JUTProcBar_setVisibleHeapBar(JC_JUTProcBar_getManager(), FALSE);
    jc_gport = JC_J2DOrthoGraph_new();
    GXColor color = TCOLOR_BLACK;
    jc_fader = JC_JUTFader_new(0, 0, (u16)JC_JUTVideo_getFbWidth(JC_JUTVideo_getManager()),
                               (u16)JC_JUTVideo_getEfbHeight(JC_JUTVideo_getManager()), (u32*)&color);
    JC_JFWDisplay_setFader(display_manager, jc_fader);
    JC_JFWDisplay_setClearColor(display_manager, TCOLOR_BLACK);
    JC_JFWDisplay_setGamma(display_manager, 0);
    JW_SetVideoPan(20, 6, 598, 464);
    VIConfigurePan(20, 6, 598, 464);
    JC_JKRExpHeap_changeGroupID(JC_JFWSystem_getSystemHeap(), 2);
}

